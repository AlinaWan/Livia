namespace Livia.Utils.MessageBox;

/// <summary>
/// Enumeration for message box default buttons.
/// </summary>
public enum MessageBoxDefaultButton : uint
{
    /// <summary>
    /// The first button is the default.
    /// </summary>
    Button1 = 0x00000000,

    /// <summary>
    /// The second button is the default.
    /// </summary>
    Button2 = 0x00000100,

    /// <summary>
    /// The third button is the default.
    /// </summary>
    Button3 = 0x00000200,

    /// <summary>
    /// The fourth button is the default.
    /// </summary>
    Button4 = 0x00000300
}